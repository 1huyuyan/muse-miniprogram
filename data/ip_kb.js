// 归一化：小写、去空格/点/括号，便于互通
function norm(s) {
  return String(s || '').toLowerCase().replace(/[\s·・.。()（）]/g, '');
}

function findIpEntry(ip) {
  const name = ip && (typeof ip === 'string' ? ip : ip.name);
  if (!name) return null;
  const n = norm(name);
  if (!n) return null;
  const keys = Object.keys(IP_KB);
  // 第一遍：完全相等优先（避免短别名/子串误命中，如 KAI 与 Jujutsu Kaisen 均含 kai）
  for (let i = 0; i < keys.length; i++) {
    const e = IP_KB[keys[i]];
    const cands = [e.key, e.name].concat(e.aliases || []);
    for (let j = 0; j < cands.length; j++) {
      if (norm(cands[j]) === n) return e;
    }
  }
  // 第二遍：子串宽容匹配（昵称/别名部分命中）
  for (let i = 0; i < keys.length; i++) {
    const e = IP_KB[keys[i]];
    const cands = [e.key, e.name].concat(e.aliases || []);
    for (let j = 0; j < cands.length; j++) {
      const c = norm(cands[j]);
      if (c && (c.indexOf(n) >= 0 || n.indexOf(c) >= 0)) return e;
    }
  }
  return null;
}

module.exports = { IP_KB, findIpEntry };
